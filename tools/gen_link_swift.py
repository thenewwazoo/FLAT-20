# mac/Sources/FlatLink/Generated.swift from firmware/src/ms20.h and ms20_link.h: the panel app's lists of knobs and jacks,
# in the firmware's order, so the two cannot drift apart.
#   gen_link_swift.py            write it
#   gen_link_swift.py --check    exit 1 if the file is not what it would write (tests/run_tests.sh)
import re, sys, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "mac/Sources/FlatLink/Generated.swift")

def enum_names(src, first):
    """the names of the C enum whose first member is `first`, in order (MS_N* counts excluded)"""
    m = re.search(r"enum\s*\{([^}]*\b" + first + r"\b[^}]*)\}", src)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    names = [n.strip().split("=")[0].strip() for n in body.split(",") if n.strip()]
    return [n for n in names if not n.startswith("MS_N")]

def define(src, name):
    return re.search(r"#define\s+" + name + r"\s+(\w+)", src).group(1).rstrip("u")

def main():
    h = open(os.path.join(ROOT, "firmware/src/ms20.h")).read()
    l = open(os.path.join(ROOT, "firmware/src/ms20_link.h")).read()
    params, srcs, dsts = enum_names(h, "P_V1WAVE"), enum_names(h, "SRC_NONE"), enum_names(h, "DST_NONE")
    ncable = define(h, "MS_NCABLE")
    def camel(n, prefix):
        parts = n[len(prefix):].lower().split("_")
        return parts[0] + "".join(p.capitalize() for p in parts[1:])
    o = ["// Generated by tools/gen_link_swift.py from firmware/src/ms20.h and ms20_link.h. Do not edit.", "",
         "public enum LinkFormat {",
         "    public static let version: UInt8 = %s" % define(l, "LINK_VERSION"),
         "    public static let id: UInt8 = 0x%s" % define(l, "LINK_ID")[2:],
         "    public static let state: UInt8 = %s" % define(l, "LINK_STATE"),
         "    public static let live: UInt8 = %s" % define(l, "LINK_LIVE"),
         "    /// computer -> FM-1: the whole patch panel",
         "    public static let cableSet: UInt8 = %s" % define(l, "LINK_CABLES"),
         "    /// STATE's flag: this firmware takes CABLES",
         "    public static let takesCables: UInt8 = %s" % define(l, "LINK_TAKES_CABLES"),
         "    public static let cables = %s" % ncable,
         "}", "",
         "/// the FM-1's knobs and switches, in the firmware's order (ms20.h, P_*)",
         "public enum Param: Int, CaseIterable, Sendable {"]
    o += ["    case %s = %d" % (camel(n, "P_"), i) for i, n in enumerate(params)]
    o += ["}", "", "/// the patch panel's outputs (ms20.h, SRC_*); none = no cable", "public enum Source: Int, CaseIterable, Sendable {"]
    o += ["    case %s = %d" % (camel(n, "SRC_"), i) for i, n in enumerate(srcs)]
    o += ["}", "", "/// the patch panel's inputs (ms20.h, DST_*)", "public enum Destination: Int, CaseIterable, Sendable {"]
    o += ["    case %s = %d" % (camel(n, "DST_"), i) for i, n in enumerate(dsts)]
    o += ["}", ""]
    text = "\n".join(o)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("Generated.swift is %s" % ("up to date" if ok else "OUT OF DATE: run tools/gen_link_swift.py"))
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT, len(params), "params,", len(srcs), "sources,", len(dsts), "destinations")

if __name__ == "__main__":
    main()
